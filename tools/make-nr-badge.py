"""make-nr-badge.py: images/nr-on-badge.png -> OptiScaler/menu/font/NrOnBadge.h, the "NR ON" badge drawn while NR runs.

640 px wide, RGBA, run-length encoded as (count, colour) pairs; MenuCommon::RenderNrBadge unpacks it into the font atlas.
"""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
im = Image.open(root / 'images/nr-on-badge.png').convert('RGBA')
im = im.crop(im.getchannel('A').getbbox())
w = 640
h = round(im.height * w / im.width)
im = im.resize((w, h), Image.LANCZOS)
runs = []
for r, g, b, a in im.get_flattened_data():
    v = r | g << 8 | b << 16 | a << 24 if a else 0
    if runs and runs[-1][1] == v and runs[-1][0] < 0xFFFF:
        runs[-1][0] += 1
    else:
        runs.append([1, v])
words = [f'{n},0x{v:08X}' for n, v in runs]
lines = [','.join(words[i:i + 8]) for i in range(0, len(words), 8)]
(root / 'OptiScaler/menu/font/NrOnBadge.h').write_text(
    '// Generated by tools/make-nr-badge.py from images/nr-on-badge.png.\n#pragma once\n\n'
    f'static const int NrOnBadgeWidth = {w};\nstatic const int NrOnBadgeHeight = {h};\n'
    '// (count, colour) runs, colour as ImU32 (0xAABBGGRR).\n'
    'static const unsigned int NrOnBadgeRuns[] = {\n    ' + ',\n    '.join(lines) + '\n};\n', newline='\n')
print(w, h, len(runs))
